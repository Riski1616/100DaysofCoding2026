public class Main {
    public static void main(String[] args) {
        // Tipe data float → digunakan untuk menyimpan bilangan pecahan
        float tinggi = 155.5f; 

        // Tipe data double → digunakan untuk menyimpan bilangan pecahan dengan lebih banyak angka desimal
        double berat = 60.25; 

        System.out.println("Tinggi : " + tinggi);
        System.out.println("Berat  : " + berat);
    }
}
