public class Main {
    public static void main(String[] args) {

        // Tipe data byte: untuk menyimpan bilangan bulat kecil
        byte umur = 18;

        // Tipe data short: untuk menyimpan bilangan bulat dengan nilai lebih besar dari byte
        short tahun = 2008;

        // Tipe data int: untuk menyimpan bilangan bulat
        int nim = 90026512;

        // Tipe data long: untuk menyimpan bilangan bulat dengan nilai yang sangat besar
        long jumlahMahasiswa = 20000L;

        System.out.println("umur            :" + umur);
        System.out.println("tahun           :" + tahun);
        System.out.println("nim             :" + nim);
        System.out.println("jumlahMahasiswa :" + jumlahMahasiswa);
    }
}
