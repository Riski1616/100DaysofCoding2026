public class Main {
    public static void main(String[] args) {

        // Escape Sequence \n
        System.out.println("Nama         : Riski\nKelas        : B");

        // Escape Sequence \t
        System.out.println("Nim\t     : D0226512");
        System.out.println("Prodi\t     : Informatika");
        System.out.println("alamat\t     : Majene");

        // Escape Sequence \"
        System.out.println("Saya berkata : \"Saya sedang belajar Java\"");

        // Escape Sequence \\
        System.out.println("Lokasi file  : C:\\Java\\Belajar");

        // Escape Sequence \'
        System.out.println("Karakter     : \'A\'");
    }
}
