public class Main {
    public static void main(String[] args) {

        int umur; // Deklarasi: membuat variabel umur bertipe int

        umur = 18; // Inisialisasi: memberikan nilai awal 18
        System.out.println("sebelum diubah : " + umur); // Menampilkan nilai umur, yaitu 18

        umur = 19; // Update: mengubah nilai umur dari 18 menjadi 19
        System.out.println("sesudah diubah : "+ umur); // Menampilkan nilai umur, yaitu 19
    }
}
